-- Backup & restore + access log.
-- Run once in Supabase > SQL Editor. Safe to run again. It does NOT change or delete any existing data.

-- 1. Access log: who removed which login, backups taken, restores done.
create table if not exists public.access_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  actor text,            -- email of the committee member who did it
  action text not null,  -- e.g. login_removed, backup, restore
  target text,           -- e.g. the removed email, the backup file
  details text
);
alter table public.access_log enable row level security;
do $$ declare p record; begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'access_log' loop
    execute format('drop policy %I on public.access_log', p.policyname);
  end loop;
end $$;
-- Committee can read the log; nobody can change it from the app (the server writes it with the secret key).
create policy committee_read on public.access_log for select to authenticated using (public.is_committee());
revoke all on public.access_log from anon;

-- 2. Restore: replaces the society's records with those in a backup, all in ONE step
--    (if anything fails, nothing is changed). Only the server (secret key) can call it.
create or replace function public.restore_society_backup(p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  ins text[] := array['flats','billing_settings','signatories','events','notices','maintenance','businesses',
                      'members','emergency_contacts','vehicles','flat_docs','bills','payments'];
  t text; i int; cols text; n int; seq text; col record; result jsonb := '{}'::jsonb;
begin
  if p is null or p->>'app' is distinct from 'aakar-society' or jsonb_typeof(p->'tables') <> 'object' then
    raise exception 'This is not an Aakar Society backup file.';
  end if;
  if not (p->'tables' ? 'flats') or jsonb_array_length(p->'tables'->'flats') = 0 then
    raise exception 'The backup has no flats; restore stopped.';
  end if;
  -- remove current records, children first (only tables that are in the backup)
  for i in reverse array_length(ins, 1)..1 loop
    t := ins[i];
    if to_regclass('public.' || t) is not null and (p->'tables') ? t then
      execute format('delete from public.%I where true', t);
    end if;
  end loop;
  -- put the backup's records back, parents first
  foreach t in array ins loop
    if to_regclass('public.' || t) is null or not ((p->'tables') ? t) then continue; end if;
    if jsonb_array_length(p->'tables'->t) = 0 then result := result || jsonb_build_object(t, 0); continue; end if;
    select string_agg(quote_ident(a.attname), ',') into cols
      from pg_attribute a
     where a.attrelid = ('public.' || t)::regclass and a.attnum > 0 and not a.attisdropped and a.attgenerated = ''
       and (p->'tables'->t->0) ? a.attname;
    execute format('insert into public.%I (%s) overriding system value select %s from jsonb_populate_recordset(null::public.%I, $1)',
                   t, cols, cols, t) using p->'tables'->t;
    get diagnostics n = row_count;
    result := result || jsonb_build_object(t, n);
    -- keep running numbers (ids) ahead of the restored rows
    for col in select a.attname from pg_attribute a
                where a.attrelid = ('public.' || t)::regclass and a.attnum > 0 and not a.attisdropped loop
      seq := pg_get_serial_sequence('public.' || t, col.attname);
      if seq is not null then
        execute format('select setval(%L, coalesce((select max(%I) from public.%I), 0) + 1, false)', seq, col.attname, t);
      end if;
    end loop;
  end loop;
  return result;
end $$;
revoke all on function public.restore_society_backup(jsonb) from public, anon, authenticated;
grant execute on function public.restore_society_backup(jsonb) to service_role;

-- 3. A removed login stops working at once. Without this, a phone that was already logged in keeps
--    access until its login token expires; now every check also confirms the login still exists.
create or replace function public.is_committee() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', 'committee') <> 'resident'
     and exists (select 1 from auth.users u where u.id = auth.uid())
$$;
create or replace function public.my_flat() returns text
language sql stable security definer set search_path = public as $$
  select case when exists (select 1 from auth.users u where u.id = auth.uid())
              then auth.jwt() -> 'app_metadata' ->> 'flat_id' end
$$;

-- 4. Check: should show access_log with 1 rule, and the restore function
select 'access_log' as item, count(*)::text as rules from pg_policies where schemaname = 'public' and tablename = 'access_log'
union all
select 'restore_society_backup', count(*)::text from pg_proc where proname = 'restore_society_backup';
